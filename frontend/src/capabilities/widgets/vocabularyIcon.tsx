// "FlaskConical" -> "flask-conical", "Building2" -> "building-2". Mirrors lucide's
// kebab-casing (letter->digit boundary also gets a dash), matching the backend names.
function toKebab(name: string): string {
  return name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
    .replace(/([a-zA-Z])([0-9])/g, "$1-$2")
    .toLowerCase();
}

// The full set of valid kebab names — exported so a test can assert it matches the
// backend ICON_VOCABULARY.
export const VOCABULARY_ICON_NAMES = new Set(Object.keys(VOCABULARY));

// The vocabulary component for a model-suggested name (PascalCase from the wire), or
// null when the model picked a name outside the vocabulary (the caller renders its
// own fallback). O(1) lookup, no dynamic import.
export function resolveVocabularyIcon(icon: string): LucideIcon | null {
  return VOCABULARY[toKebab(icon)] ?? null;
}
