// Static resolution for the model's per-entity / per-event / per-conversation icon
// picks. The model chooses ONLY from the backend's ICON_VOCABULARY (a closed,
// curated set; see backend/src/tools.ts), so we import exactly those statically and
// look them up synchronously.
//
// This deliberately REPLACES lucide-react/dynamic everywhere in the app. DynamicIcon
// lazy-imports each icon as its OWN JS chunk, which (a) made a graph/timeline with
// many distinct icons fire one network request PER icon, and (b) forced Vite to emit
// ~1600 per-icon chunks that the PWA service worker then precached on install (the
// real request storm). The whole vocabulary as static imports is a few KB folded into
// the main bundle — zero extra requests, no per-icon chunks to precache.
//
// THIS LIST MIRRORS backend/src/tools.ts ICON_VOCABULARY. Keep them in sync: every
// name here must be in that list and vice versa (there's a test that asserts it).

